using System.IO;
using System.Text;

namespace PearUI.Core;

/// <summary>
/// Short commands available inside PearUI Terminal: <c>wg</c> (winget shortcuts) and <c>update</c> (Windows Update).
/// The table below is the single source of truth: it is shown in Settings and used to generate the small scripts
/// (cmd, PowerShell and sh versions) that sit on the Terminal's PATH.
/// </summary>
public static class TerminalCommands
{
    public sealed record Wg(string Alias, string WingetArgs, string Description);

    public static readonly IReadOnlyList<Wg> WgCommands = new List<Wg>
    {
        new("l",   "list",                              "List installed apps"),
        new("i",   "install",                           "Install an app, e.g. wg i vlc"),
        new("r",   "uninstall",                         "Uninstall an app"),
        new("s",   "search",                            "Search for apps, e.g. wg s firefox"),
        new("sh",  "show",                              "Show details of an app"),
        new("u",   "upgrade",                           "List apps that have updates (or upgrade one: wg u vlc)"),
        new("ua",  "upgrade --all",                     "Upgrade every app"),
        new("uai", "upgrade --all --include-unknown",   "Upgrade every app, including ones with an unknown version"),
        new("su",  "source update",                     "Refresh the app catalog"),
        new("sl",  "source list",                       "List the app sources"),
        new("ex",  "export",                            "Export the list of installed apps to a file"),
        new("im",  "import",                            "Install the apps from an exported file"),
        new("d",   "download",                          "Download an app's installer without installing"),
        new("rp",  "repair",                            "Repair an installed app"),
        new("p",   "pin list",                          "List pinned apps (kept at their version)"),
        new("pa",  "pin add",                           "Pin an app so upgrades skip it"),
        new("pr",  "pin remove",                        "Remove a pin"),
        new("st",  "settings",                          "Open the winget settings file"),
        new("v",   "--version",                         "Show the winget version"),
    };

    public static string Directory => Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "PearUI", "shell", "bin");

    /// <summary>Writes the command scripts (safe to call every time a terminal starts; unchanged files are left alone).</summary>
    public static void Install()
    {
        try
        {
            System.IO.Directory.CreateDirectory(Directory);
            Write("wg.ps1", WgScript());
            Write("update.ps1", UpdateScript);
            foreach (var name in new[] { "wg", "update" })
            {
                Write(name + ".cmd", "@echo off\r\npowershell -NoProfile -ExecutionPolicy Bypass -File \"%~dp0" + name + ".ps1\" %*\r\n", crlf: true);
                Write(name, "#!/bin/sh\nd=\"$(cd \"$(dirname \"$0\")\" && (pwd -W 2>/dev/null || pwd))\"\nexec powershell.exe -NoProfile -ExecutionPolicy Bypass -File \"$d/" + name + ".ps1\" \"$@\"\n");
            }
        }
        catch { }
    }

    private static void Write(string file, string text, bool crlf = false)
    {
        string path = Path.Combine(Directory, file);
        text = crlf ? text.Replace("\r\n", "\n").Replace("\n", "\r\n") : text.Replace("\r\n", "\n");
        if (File.Exists(path) && File.ReadAllText(path) == text) return;
        // .ps1 needs a BOM for Windows PowerShell 5 to read non-ASCII text correctly; the sh script must not have one.
        File.WriteAllText(path, text, file.EndsWith(".ps1") ? new UTF8Encoding(true) : new UTF8Encoding(false));
    }

    // ---------- wg ----------
    private static string WgScript()
    {
        var sb = new StringBuilder();
        sb.Append("# wg: short commands for winget (generated by PearUI; changes are overwritten).\n");
        sb.Append("$map = [ordered]@{\n");
        foreach (var c in WgCommands) sb.Append($"  '{c.Alias}' = '{c.WingetArgs}'\n");
        sb.Append("}\n");
        sb.Append("$desc = @{\n");
        foreach (var c in WgCommands) sb.Append($"  '{c.Alias}' = '{c.Description.Replace("'", "''")}'\n");
        sb.Append("}\n");
        sb.Append("""
            if ($args.Count -eq 0 -or $args[0] -in @('help', '-h', '--help', '?')) {
              Write-Host 'wg: short commands for winget'
              Write-Host ''
              foreach ($k in $map.Keys) { Write-Host ('  wg {0,-4} winget {1,-34} {2}' -f $k, $map[$k], $desc[$k]) }
              Write-Host ''
              Write-Host 'Anything else is passed straight to winget, e.g. wg install --id Git.Git -e'
              return
            }
            $first = [string]$args[0]
            $rest = @()
            if ($args.Count -gt 1) { $rest = @($args[1..($args.Count - 1)]) }
            if ($map.Contains($first)) { $call = @($map[$first] -split ' ') + $rest } else { $call = @($args) }
            & winget @call
            exit $LASTEXITCODE
            """.Replace("\r\n", "\n"));
        sb.Append('\n');
        return sb.ToString();
    }

    // ---------- update ----------
    private const string UpdateScript = """
        # update: runs Windows Update from PowerShell, quietly (generated by PearUI; changes are overwritten).
        # "update" installs the regular updates; "update optional" also installs optional ones (preview updates and so on).
        $log = $null
        $optional = $false
        for ($i = 0; $i -lt $args.Count; $i++) {
          if ($args[$i] -eq '-Log' -and $i + 1 -lt $args.Count) { $log = [string]$args[$i + 1] }
          if ("$($args[$i])" -in @('-Optional', '--optional', 'optional', '-o', 'all')) { $optional = $true }
        }
        function Say([string]$text) { if ($log) { Add-Content -LiteralPath $log -Value $text } else { Write-Host $text } }

        $principal = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
        if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
          # Windows Update needs administrator rights: run it in a hidden elevated window and just report the outcome here.
          $tmp = Join-Path $env:TEMP ('pearui-update-' + [guid]::NewGuid().ToString('N') + '.log')
          Write-Host 'Updating Windows in the background (approve the administrator prompt)...'
          $argList = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', "`"$PSCommandPath`"", '-Log', "`"$tmp`"")
          if ($optional) { $argList += '-Optional' }
          try {
            Start-Process powershell -Verb RunAs -WindowStyle Hidden -Wait -ArgumentList $argList
          } catch { Write-Host 'Cancelled: administrator rights were not granted.'; return }
          if (Test-Path -LiteralPath $tmp) { Get-Content -LiteralPath $tmp | ForEach-Object { Write-Host $_ }; Remove-Item -LiteralPath $tmp -ErrorAction SilentlyContinue }
          else { Write-Host 'No result was reported.' }
          return
        }

        try {
          $session = New-Object -ComObject Microsoft.Update.Session
          $searcher = $session.CreateUpdateSearcher()
          $regular = $searcher.Search('IsInstalled=0 and IsHidden=0 and Type=''Software''')
          $extra = $searcher.Search('IsInstalled=0 and IsHidden=0 and DeploymentAction=''OptionalInstallation''')
          $todo = @(); foreach ($u in $regular.Updates) { $todo += $u }
          $ids = @($todo | ForEach-Object { $_.Identity.UpdateID })
          $optionalOnly = @(); foreach ($u in $extra.Updates) { if ($ids -notcontains $u.Identity.UpdateID) { $optionalOnly += $u } }
          if ($optional) { $todo += $optionalOnly }

          if ($todo.Count -eq 0) { Say 'Windows is up to date.' }
          else {
            $all = New-Object -ComObject Microsoft.Update.UpdateColl
            foreach ($u in $todo) {
              if (-not $u.EulaAccepted) { $u.AcceptEula() }
              [void]$all.Add($u)
            }
            $dl = $session.CreateUpdateDownloader()
            $dl.Updates = $all
            [void]$dl.Download()
            $ready = New-Object -ComObject Microsoft.Update.UpdateColl
            foreach ($u in $todo) { if ($u.IsDownloaded) { [void]$ready.Add($u) } }
            if ($ready.Count -eq 0) { Say 'Found updates but none could be downloaded.' }
            else {
              $inst = $session.CreateUpdateInstaller()
              $inst.Updates = $ready
              $res = $inst.Install()
              $names = @{ 0 = 'not started'; 1 = 'in progress'; 2 = 'succeeded'; 3 = 'succeeded with errors'; 4 = 'failed'; 5 = 'aborted' }
              Say ('Installed {0} update(s): {1}.' -f $ready.Count, $names[[int]$res.ResultCode])
              foreach ($u in $ready) { Say ('  ' + $u.Title) }
              if ($res.RebootRequired) { Say 'Restart your PC to finish installing updates.' }
            }
          }

          if (-not $optional -and $optionalOnly.Count -gt 0) {
            Say 'Optional updates are available (run "update all" to install them):'
            foreach ($u in $optionalOnly) { Say ('  ' + $u.Title) }
          }
        }
        catch { Say ('Windows Update failed: ' + $_.Exception.Message) }
        """;
}
